-- 6. DOES TENURE AFFECT CUSTOMER CHURN ? --
SELECT 
CASE
        WHEN TENURE_MONTHS <= 12 THEN '0-12 Months'
        WHEN TENURE_MONTHS <= 24 THEN '13-24 Months'
        WHEN TENURE_MONTHS <= 48 THEN '25-48 Months'
        ELSE '49+ Months'
END AS TENURE_GROUP,
COUNT(*) AS TOTAL_CUSTOMERS,
SUM( CASE WHEN `CHURN_LABEL` = 'YES' THEN 1 END ) AS CUSTOMER_CHURN,
ROUND(
	SUM( CASE WHEN `CHURN_LABEL` = 'YES' THEN 1 END ) * 100.0 / COUNT(*) , 2) AS CHURN_RATE
FROM CUSTOMER_CHURN
GROUP BY TENURE_GROUP
ORDER BY CHURN_RATE DESC;


