-- 1. TOTAL NO OF CUSTOMERS --
SELECT 
COUNT(*)  AS TOTAL_CUSTOMERS
FROM CUSTOMER_CHURN;

SELECT * FROM CUSTOMER_CHURN;


-- 2. HOW MANY CUSTOMERS HAVE CHURNED --
SELECT
COUNT(*) AS CHURNED_CUSTOMERS
FROM  CUSTOMER_CHURN
WHERE CHURN_LABEL = 'YES';


-- 3. WHAT IS THE OVERALL CHURN_RATE --
SELECT
	COUNT(CASE WHEN  CHURN_LABEL = 'YES' THEN 1 END) * 100.0
	/ COUNT(*) AS CHURN_RATE
FROM CUSTOMER_CHURN;


-- 4. WHAT IS THE CHURN RATE BY CONTRACT TYPE --
SELECT
	CONTRACT,
    COUNT(*) AS TOTAL_CUSTOMERS,
	SUM( CASE WHEN `CHURN_LABEL` = 'YES' THEN 1 END ) AS CUSTOMER_CHURN,
	ROUND(
		SUM( CASE WHEN `CHURN_LABEL` = 'YES' THEN 1 END ) * 100.0 / COUNT(*) , 2) AS CHURN_RATE
FROM CUSTOMER_CHURN
GROUP BY CONTRACT 
ORDER BY CHURN_RATE DESC;


