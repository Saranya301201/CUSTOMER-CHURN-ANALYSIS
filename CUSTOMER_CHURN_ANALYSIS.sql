-- 12. WHICH CUSTOMER SEGEMENT GENERATES THE HIGHEST REVENUE ? --
SELECT
CONTRACT,
ROUND(SUM(MONTHLY_CHARGES) , 2) AS TOTAL_MONTHLY_REVENUE,
ROUND(AVG(MONTHLY_CHARGES) , 2) AS AVG_MONTHLY_CHARGE
FROM CUSTOMER_CHURN
GROUP BY CONTRACT
ORDER BY TOTAL_MONTHLY_REVENUE DESC;


-- 13. HOW MUCH REVENUE IS ASSOCIATED WITH CHURNED CUSTOMERS ? --
SELECT
ROUND(SUM(MONTHLY_CHARGES) , 2) AS MONTHLY_REVENUE_RISK
FROM CUSTOMER_CHURN
WHERE CHURN_LABEL = 'YES';


